function seekTo(value) {
  if (!Number.isFinite(audio.duration) || audio.duration <= 0) return;

  const percent = Math.max(0, Math.min(100, Number(value)));
  audio.currentTime = (percent / 100) * audio.duration;
  updateProgress();
}

[progress, modalProgress].forEach((slider) => {
  slider.addEventListener("input", () => {
    isSeeking = true;

    const value = Number(slider.value);
    progress.value = String(value);
    modalProgress.value = String(value);

    const total = Number.isFinite(audio.duration) ? audio.duration : 0;
    const previewTime = total ? (value / 100) * total : 0;

    currentTime.textContent = formatTime(previewTime);
    modalCurrentTime.textContent = formatTime(previewTime);
  });

  slider.addEventListener("change", () => {
    seekTo(slider.value);
    isSeeking = false;
    updateProgress();
  });
});

