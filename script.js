const $ = (id) => document.getElementById(id);

const songsGrid = $("songsGrid");
const songsCount = $("songsCount");
const lyricsModal = $("lyricsModal");

const playerTitle = $("playerTitle");
const playerCover = $("playerCover");
const playBtn = $("playBtn");
const prevBtn = $("prevBtn");
const nextBtn = $("nextBtn");
const progress = $("progress");
const currentTime = $("currentTime");
const duration = $("duration");
const volume = $("volume");
const volumeIcon = $("volumeIcon");

const modalTitle = $("modalTitle");
const modalCover = $("modalCover");
const lyricsText = $("lyricsText");
const modalPlayBtn = $("modalPlayBtn");
const modalProgress = $("modalProgress");
const modalCurrentTime = $("modalCurrentTime");
const modalDuration = $("modalDuration");
const modalVolume = $("modalVolume");
const modalVolumeIcon = $("modalVolumeIcon");

let currentIndex = -1;
let isSeeking = false;
let modalIsOpen = false;

function formatTime(seconds) {
  if (!Number.isFinite(seconds) || seconds < 0) return "0:00";

  const mins = Math.floor(seconds / 60);
  const secs = Math.floor(seconds % 60);

  return `${mins}:${String(secs).padStart(2, "0")}`;
}

function getCurrentSong() {
  return songs[currentIndex] || null;
}

function renderSongs() {
  songsCount.textContent = `${songs.length} أغنية`;

  songsGrid.innerHTML = songs.map((song, index) => `
    <article class="song-card">
      <div class="song-cover-wrap">
        <img
          class="song-cover"
          src="${song.cover}"
          alt="${song.title}"
          loading="lazy"
          onerror="this.style.opacity='0.15'"
        >
      </div>

      <h3>${song.title}</h3>
      <p class="song-artist">Nader Elbahnsawy · ${song.duration}</p>

      <div class="song-card-actions">
        <button type="button" data-play="${index}">▶ تشغيل</button>
        <button type="button" data-lyrics="${index}">الكلمات</button>
      </div>
    </article>
  `).join("");
}

function updatePlayButtons() {
  const playing = !audio.paused;

  playBtn.textContent = playing ? "⏸" : "▶";
  modalPlayBtn.textContent = playing ? "⏸" : "▶";

  playBtn.setAttribute("aria-label", playing ? "إيقاف مؤقت" : "تشغيل");
  modalPlayBtn.setAttribute("aria-label", playing ? "إيقاف مؤقت" : "تشغيل");
}

function updateVolumeIcons() {
  const muted = audio.volume === 0;
  const iconMarkup = muted
    ? '<svg viewBox="0 0 24 24" aria-hidden="true"><path d="M4 9v6h4l5 4V5L8 9H4Z"/><path d="m17 9 5 6m0-6-5 6"/></svg>'
    : '<svg viewBox="0 0 24 24" aria-hidden="true"><path d="M3 9v6h4l5 4V5L7 9H3Z"/><path class="sound-arc arc-one" d="M15 9a5 5 0 0 1 0 6"/><path class="sound-arc arc-two" d="M18 6a9 9 0 0 1 0 12"/></svg>';
  [volumeIcon, modalVolumeIcon].forEach((icon) => {
    icon.innerHTML = iconMarkup;
    icon.classList.toggle("is-muted", muted);
    icon.setAttribute("aria-label", muted ? "تشغيل الصوت" : "كتم الصوت");
    icon.setAttribute("role", "button");
    icon.setAttribute("tabindex", "0");
  });
}

function syncVolumeControls(value) {
  const safeValue = Math.max(0, Math.min(1, Number(value)));

  audio.volume = safeValue;
  volume.value = String(safeValue);
  modalVolume.value = String(safeValue);

  updateVolumeIcons();
}

function updateDurationDisplay() {
  const song = getCurrentSong();
  const shownDuration = Number.isFinite(audio.duration) && audio.duration > 0
    ? audio.duration
    : 0;

  const text = shownDuration ? formatTime(shownDuration) : (song?.duration || "0:00");

  duration.textContent = text;
  modalDuration.textContent = text;
}

function updateProgress() {
  const current = Number.isFinite(audio.currentTime) ? audio.currentTime : 0;
  const total = Number.isFinite(audio.duration) && audio.duration > 0
    ? audio.duration
    : 0;

  const percent = total ? (current / total) * 100 : 0;

  if (!isSeeking) {
    progress.value = String(percent);
    modalProgress.value = String(percent);
  }

  currentTime.textContent = formatTime(current);
  modalCurrentTime.textContent = formatTime(current);

  updateDurationDisplay();
}

function setSongInfo(song) {
  playerTitle.textContent = song.title;
  playerCover.src = song.cover;
  playerCover.alt = song.title;

  modalTitle.textContent = song.title;
  modalCover.src = song.cover;
  modalCover.alt = song.title;

  lyricsText.textContent = song.lyrics || "مفيش كلمات مضافة للأغنية دي لسه.";

  progress.value = "0";
  modalProgress.value = "0";
  currentTime.textContent = "0:00";
  modalCurrentTime.textContent = "0:00";

  updateDurationDisplay();
}

async function playSong(index, shouldPlay = true) {
  if (index < 0 || index >= songs.length) return;

  const sameSong = currentIndex === index;
  currentIndex = index;

  if (!sameSong) {
    audio.pause();
    audio.src = songs[index].audio;
    audio.load();
    setSongInfo(songs[index]);
  }

  if (shouldPlay) {
    try {
      await audio.play();
    } catch (error) {
      console.warn("تعذر تشغيل الأغنية. تأكد من اسم الملف ومساره:", songs[index].audio);
      updatePlayButtons();
    }
  } else {
    audio.pause();
  }

  updatePlayButtons();
  updateProgress();
}

function togglePlayback() {
  if (currentIndex === -1) {
    playSong(0, true);
    return;
  }

  if (audio.paused) {
    audio.play().catch(() => {
      console.warn("تعذر تشغيل الملف الصوتي. راجع مسار الأغنية.");
    });
  } else {
    audio.pause();
  }
}

function playNext() {
  const nextIndex = currentIndex < 0 ? 0 : (currentIndex + 1) % songs.length;
  playSong(nextIndex, true);
}

function playPrevious() {
  if (audio.currentTime > 3) {
    audio.currentTime = 0;
    updateProgress();
    return;
  }

  const previousIndex = currentIndex <= 0 ? songs.length - 1 : currentIndex - 1;
  playSong(previousIndex, true);
}

function openLyrics(index = currentIndex) {
  if (index < 0 || index >= songs.length) {
    index = 0;
  }

  const needsToPlay = currentIndex !== index;

  if (needsToPlay) {
    playSong(index, false);
  } else {
    setSongInfo(songs[index]);
  }

  modalIsOpen = true;
  lyricsModal.classList.remove("is-opening");
  lyricsModal.classList.add("is-open", "is-opening");
  lyricsModal.setAttribute("aria-hidden", "false");
  window.clearTimeout(window.lyricsTrackIntroTimer);
  window.lyricsTrackIntroTimer = window.setTimeout(() => {
    lyricsModal.classList.remove("is-opening");
  }, 1150);
  document.body.style.overflow = "hidden";

  lyricsText.scrollTop = 0;
  syncVolumeControls(audio.volume);
  updatePlayButtons();
}

function closeLyrics() {
  modalIsOpen = false;
  lyricsModal.classList.remove("is-open", "is-opening");
  lyricsModal.setAttribute("aria-hidden", "true");
  document.body.style.overflow = "";
}

songsGrid.addEventListener("click", (event) => {
  const playButton = event.target.closest("[data-play]");
  const lyricsButton = event.target.closest("[data-lyrics]");

  if (playButton) {
    playSong(Number(playButton.dataset.play), true);
  }

  if (lyricsButton) {
    openLyrics(Number(lyricsButton.dataset.lyrics));
  }
});

